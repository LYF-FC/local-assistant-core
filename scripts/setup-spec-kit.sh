#!/usr/bin/env bash
set -euo pipefail

SPECIFY_VERSION="1.2.3"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

log() { printf '\n[spec-kit] %s\n' "$*"; }
die() { printf '\n[spec-kit] ERROR: %s\n' "$*" >&2; exit 1; }

command -v uv >/dev/null 2>&1 || die "uv is required. Install uv, then re-run this script."

CANONICAL_CONSTITUTION="$(mktemp)"
trap 'rm -f "$CANONICAL_CONSTITUTION"' EXIT

if [[ -f .specify/memory/constitution.md ]]; then
  cp .specify/memory/constitution.md "$CANONICAL_CONSTITUTION"
fi

log "Installing Spec Kit CLI $SPECIFY_VERSION"
uv tool install "specify-cli==$SPECIFY_VERSION" --force

log "Initializing Spec Kit in the existing Butler repository"
specify init --here --force --non-interactive --integration codex --ignore-agent-tools --script sh

if [[ -s "$CANONICAL_CONSTITUTION" ]]; then
  log "Restoring Butler's canonical constitution"
  mkdir -p .specify/memory
  cp "$CANONICAL_CONSTITUTION" .specify/memory/constitution.md
fi

log "Installing bug-fixing extension"
specify extension add bug

log "Installing idea-assessment extension"
specify extension add assess

log "Verifying installation"
specify version
specify self check || true

cat <<'EOF'

Spec Kit is initialized.

First Butler feature:
  specs/001-identity-permissions-audit/spec.md

To select it for the current shell:
  export SPECIFY_FEATURE_DIRECTORY=specs/001-identity-permissions-audit

Then continue with the project-local Codex skills, starting with:
  $speckit-clarify
  $speckit-plan

Review and commit any official Spec Kit scaffolding generated by this script.
EOF
